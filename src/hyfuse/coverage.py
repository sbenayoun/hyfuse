"""coverage.py (T1.7): coverage audit from the DASC index -> reports/coverage.md.

Runs off hylogger_dataset_index only (no NVCL downloads). Counts holes with
SWIR / TIR / both / logging / assays / petrophysics, broken down by processing
level and commodity, and evaluates GATE 1.

Evidenced interpretation (reports/data_notes.md):
- SWIR (VNIR-SWIR) is the base HyLogger instrument -> assume present for every
  index hole. (SCAN_DATE is only sparsely populated: 113/2019, so it is NOT a
  reliable SWIR flag; VERIFY SWIR mineral results per shortlisted hole as done
  on ETG0187.)
- TIR presence proxy = SCDATE_TIR populated (needs HyLogger 3+).
- Presence flags Collar/Survey/Assay/Logging_data are TEXT '0'/'1' (Survey has a
  stray '#N/A'); Geophysics_data is 'TBC' for all rows -> petrophysics coverage
  is UNKNOWN from the index.
- Level 2 processing proxy = LEV2_REL_D populated.

GATE 1: if < ~8 holes have TIR + (logging OR assays), recommend switching the
headline to single-view robustness. Expected PASS.
"""

from __future__ import annotations

import logging
from pathlib import Path

import duckdb

log = logging.getLogger("hyfuse.coverage")

ROOT = Path(__file__).resolve().parent.parent.parent
DASC_SQLITE = ROOT / "data" / "raw" / "dasc" / "HyLogger_Dataset_Package.sqlite"
REPORTS = ROOT / "reports"

GATE1_MIN_HOLES = 8

# Reusable SQL fragments (TEXT flags; treat '1' as present).
HAS_TIR = "SCDATE_TIR IS NOT NULL AND SCDATE_TIR <> ''"
HAS_LEV2 = "LEV2_REL_D IS NOT NULL AND LEV2_REL_D <> ''"
HAS_ASSAY = "Assay_data = '1'"
HAS_LOG = "Logging_data = '1'"
HAS_COLLAR = "Collar_data = '1'"
HAS_SURVEY = "Survey_data = '1'"


def _con() -> duckdb.DuckDBPyConnection:
    if not DASC_SQLITE.exists():
        raise FileNotFoundError(
            f"DASC sqlite not found at {DASC_SQLITE}. Extract it first (T1.5)."
        )
    con = duckdb.connect()
    con.execute("INSTALL sqlite; LOAD sqlite;")
    con.execute(f"ATTACH '{DASC_SQLITE}' AS dasc (TYPE sqlite, READ_ONLY);")
    return con


def _scalar(con, where: str) -> int:
    q = f"SELECT count(*) FROM dasc.hylogger_dataset_index WHERE {where}"
    return int(con.execute(q).fetchone()[0])


def build_coverage_md() -> Path:
    con = _con()
    total = int(con.execute(
        "SELECT count(*) FROM dasc.hylogger_dataset_index").fetchone()[0])

    # Headline populations.
    n_tir = _scalar(con, HAS_TIR)
    n_lev2 = _scalar(con, HAS_LEV2)
    n_assay = _scalar(con, HAS_ASSAY)
    n_log = _scalar(con, HAS_LOG)
    n_collar = _scalar(con, HAS_COLLAR)
    n_survey = _scalar(con, HAS_SURVEY)
    n_tir_label = _scalar(con, f"{HAS_TIR} AND ({HAS_LOG} OR {HAS_ASSAY})")
    n_full = _scalar(con, f"{HAS_TIR} AND {HAS_ASSAY} AND {HAS_LOG}")
    n_full_lev2 = _scalar(con, f"{HAS_TIR} AND {HAS_ASSAY} AND {HAS_LOG} AND {HAS_LEV2}")

    # Commodity breakdown of the full-headline population.
    commodity = con.execute(f"""
        SELECT COALESCE(NULLIF(Commodity_vocab,''),'(unspecified)') AS commodity,
               count(*) AS n
        FROM dasc.hylogger_dataset_index
        WHERE {HAS_TIR} AND {HAS_ASSAY} AND {HAS_LOG}
        GROUP BY 1 ORDER BY n DESC, commodity LIMIT 15
    """).fetchall()

    # Database (WAMEX/WAPIMS/CIMS) breakdown.
    dbs = con.execute("""
        SELECT COALESCE(NULLIF(Database,''),'(null)') AS db, count(*) n
        FROM dasc.hylogger_dataset_index GROUP BY 1 ORDER BY n DESC
    """).fetchall()

    gate1_pass = n_tir_label >= GATE1_MIN_HOLES

    REPORTS.mkdir(parents=True, exist_ok=True)
    out = REPORTS / "coverage.md"
    lines: list[str] = []
    lines.append("# HyFuse coverage audit (T1.7)\n")
    lines.append("Generated by `src/hyfuse/coverage.py` from the DASC "
                 "`hylogger_dataset_index` (no NVCL downloads).\n")
    lines.append("\n## Totals\n")
    lines.append(f"- Total HyLogger holes in index: **{total}**")
    lines.append(f"- SWIR (VNIR-SWIR base instrument): assumed **all {total}** "
                 "(VERIFY mineral results per shortlisted hole)")
    lines.append(f"- TIR (SCDATE_TIR populated): **{n_tir}**")
    lines.append(f"- Level 2 processing (LEV2_REL_D): **{n_lev2}**")
    lines.append(f"- Collar data: **{n_collar}**  | Survey data: **{n_survey}**")
    lines.append(f"- Logging data: **{n_log}**  | Assay data: **{n_assay}**")
    lines.append("- Petrophysics/Geophysics: **unknown** "
                 "(index `Geophysics_data` = 'TBC' for all rows)")
    lines.append("\n## Headline populations (the four-arm ablation needs TIR)\n")
    lines.append(f"- TIR **and** (logging **or** assays): **{n_tir_label}**  "
                 "← GATE 1 population")
    lines.append(f"- TIR **and** assays **and** logging: **{n_full}**")
    lines.append(f"- TIR **and** assays **and** logging **and** Level 2: "
                 f"**{n_full_lev2}**")
    lines.append("\n## Full-headline population by commodity "
                 "(TIR + assays + logging)\n")
    lines.append("| commodity | holes |")
    lines.append("|---|---:|")
    for c, n in commodity:
        lines.append(f"| {c} | {n} |")
    lines.append("\n## Source database\n")
    lines.append("| database | holes |")
    lines.append("|---|---:|")
    for db, n in dbs:
        lines.append(f"| {db} | {n} |")

    lines.append("\n## GATE 1\n")
    lines.append(f"- Threshold: >= {GATE1_MIN_HOLES} holes with TIR + "
                 "(logging or assays).")
    lines.append(f"- Observed: **{n_tir_label}**.")
    if gate1_pass:
        lines.append("- **RESULT: PASS** — proceed with the four-arm "
                     "SWIR/TIR fusion ablation (full headline).")
    else:
        lines.append("- **RESULT: FAIL** — switch the headline to "
                     "'robustness of single-view domains to processing level "
                     "and view'. Stop and confirm with the human.")
    lines.append("\n### Caveats\n")
    lines.append("- SWIR presence assumed from the base instrument, not a flag; "
                 "confirm SWIR mineral results per shortlisted hole.")
    lines.append("- SCDATE_TIR is populated for nearly all holes "
                 f"({n_tir}/{total}); treat as first-pass, confirm usable TIR "
                 "results on shortlisted holes from the TSG package.")
    lines.append("- Assay coverage is selection-biased (companies sample "
                 "prospective intervals).")
    lines.append("- 'metres after masking' per hole is reported by "
                 "`make features` once holes are fetched (needs TSG data).")
    out.write_text("\n".join(lines) + "\n")

    log.info("coverage.md written: TIR+label=%d, full=%d, gate1=%s",
             n_tir_label, n_full, "PASS" if gate1_pass else "FAIL")
    return out


def main() -> int:
    logging.basicConfig(level=logging.INFO,
                        format="%(asctime)s %(levelname)s %(message)s")
    path = build_coverage_md()
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
